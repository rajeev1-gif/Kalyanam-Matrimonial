import React, { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { Sparkles, Sliders } from 'lucide-react';
import { searchService } from '../../services/searchService';
import ProfileCard from '../../components/common/ProfileCard';

export default function RecommendedMatchesPage() {
  const [matches, setMatches] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    async function fetchRecommended() {
      try {
        const res = await searchService.getRecommendedMatches();
        if (res.success) setMatches(res.data || []);
      } catch (err) {
        console.error(err);
      } finally {
        setLoading(false);
      }
    }
    fetchRecommended();
  }, []);

  return (
    <div className="space-y-6 max-w-6xl">
      <div className="border-b border-gold-200/80 pb-4 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="font-serif text-2xl font-bold text-charcoal-900 flex items-center gap-2">
            <Sparkles className="w-6 h-6 text-gold-600" />
            Recommended Matches For You
          </h1>
          <p className="text-xs text-gray-500 mt-0.5">
            Profiles generated by our intelligent matchmaking algorithm based on your Partner Preferences
          </p>
        </div>
        <Link
          to="/dashboard/edit-profile"
          className="text-xs font-semibold text-primary-800 hover:text-primary-950 flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-gold-300 hover:bg-gold-50 transition w-fit"
        >
          <Sliders className="w-3.5 h-3.5" />
          Edit Partner Preferences
        </Link>
      </div>

      {loading ? (
        <div className="text-center py-20 text-xs text-gray-500">Curating recommendations...</div>
      ) : matches.length === 0 ? (
        <div className="bg-white p-12 rounded-3xl border border-gold-200 text-center space-y-3">
          <p className="text-xs text-gray-500">No matches found for your exact criteria.</p>
          <Link to="/search" className="inline-block px-5 py-2 bg-primary-800 text-white rounded-xl text-xs font-bold">
            Browse All Profiles
          </Link>
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6">
          {matches.map((profile) => (
            <ProfileCard key={profile.id} profile={profile} />
          ))}
        </div>
      )}
    </div>
  );
}

